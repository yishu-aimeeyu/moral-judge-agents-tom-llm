#!/usr/bin/env python3
"""E7c pre-run guard: refuse to run an experiment against a working tree that can't be cited.

WHY. E6b's numbers are in the repository but the script that produced them is not, and E5a's
compute machinery was never committed either. A result whose code state cannot be named is not
reproducible, however carefully the thresholds were pre-registered. This guard makes that failure
mode loud at the moment it matters -- before the GPU spend -- instead of months later.

WHAT COUNTS AS BLOCKING. Not everything dirty can change a result. The guard distinguishes:

  * BLOCKING -- a modified or untracked file that the run actually depends on: the script itself,
    the modules it loads, `code/tom_common.py`, and `dataset/`. If any of these is dirty the run
    aborts, because the numbers could not afterwards be attributed to a commit.
  * REPORTED -- anything else dirty. It is printed and recorded in the run log so the provenance
    note can state exactly what the tree looked like, but it does not block: `outputs/` is
    regenerated by definition, and unrelated scripts cannot reach into this run.

`--allow-dirty` exists for the transitional case where a known-irrelevant file is dirty, and it
requires the caller to say so in the log rather than silently proceeding.
"""
import os
import subprocess

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))

# Files every experiment run depends on regardless of which script is executing.
ALWAYS = ["code/tom_common.py", "dataset/master/moral_2x2_master.csv"]


def _git(*args, raw=False):
    out = subprocess.run(["git", "-C", ROOT, *args], capture_output=True,
                         text=True, check=False).stdout
    # porcelain status encodes state in the first two columns, so leading whitespace on the
    # first line is data, not padding: only strip it when the caller wants a scalar.
    return out.rstrip("\n") if raw else out.strip()


def head_commit():
    return _git("rev-parse", "--short", "HEAD") or "unknown"


def dirty_paths():
    """(path, status) for every tracked modification and every non-ignored untracked file."""
    out = []
    for line in _git("status", "--porcelain", raw=True).splitlines():
        if not line.strip():
            continue
        status, path = line[:2].strip(), line[2:].strip().strip('"')
        if "->" in path:                       # renames report "old -> new"
            path = path.split("->")[-1].strip()
        out.append((path, status))
    return out


def dependency_set(script_rel, extra=()):
    """The files this run's result depends on: the script, its sibling loads, and ALWAYS."""
    deps = {script_rel, *ALWAYS, *extra}
    p = os.path.join(ROOT, script_rel)
    if os.path.exists(p):
        src = open(p, encoding="utf-8").read()
        # sibling modules are pulled in by _load(...) / spec_from_file_location on a filename
        for token in src.split('"'):
            if token.endswith(".py") and "/" not in token and token != os.path.basename(p):
                cand = os.path.join("code", "experiments", token)
                if os.path.exists(os.path.join(ROOT, cand)):
                    deps.add(cand)
    return deps


def require_clean_tree(script_name, extra_deps=(), allow_dirty=False):
    """Abort unless every file this run depends on is committed. Returns a provenance dict."""
    script_rel = os.path.join("code", "experiments", script_name)
    deps = dependency_set(script_rel, extra_deps)
    dirty = dirty_paths()
    blocking = [(p, s) for p, s in dirty if p in deps]
    other = [(p, s) for p, s in dirty if p not in deps]

    print(f"[guard] HEAD = {head_commit()}; {len(dirty)} dirty path(s), "
          f"{len(blocking)} of them in this run's dependency set", flush=True)
    if other:
        print(f"[guard] not blocking ({len(other)} paths outside the dependency set; "
              f"see _handoff/DIRTY_FILES_TRIAGE.md):", flush=True)
        for p, s in other[:8]:
            print(f"[guard]   {s:2} {p}", flush=True)
        if len(other) > 8:
            print(f"[guard]   ... and {len(other) - 8} more", flush=True)
    if blocking:
        msg = "\n".join(f"  {s:2} {p}" for p, s in blocking)
        if not allow_dirty:
            raise SystemExit(
                f"[guard] REFUSING TO RUN: {len(blocking)} file(s) this run depends on are "
                f"uncommitted, so its numbers could not be attributed to a commit:\n{msg}\n"
                f"[guard] Commit them, or pass --allow-dirty and state in the log why the "
                f"difference cannot affect the result.")
        print(f"[guard] --allow-dirty: proceeding with {len(blocking)} dirty dependency file(s):"
              f"\n{msg}", flush=True)
    else:
        print("[guard] every dependency of this run is committed.", flush=True)
    return dict(head=head_commit(), n_dirty=len(dirty), blocking=blocking, other=other)


if __name__ == "__main__":
    import sys
    name = sys.argv[1] if len(sys.argv) > 1 else "67_e6b_orthogonalized.py"
    require_clean_tree(name, allow_dirty="--allow-dirty" in sys.argv)
