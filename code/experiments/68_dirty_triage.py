def git(*args, raw=False):
    out = subprocess.run(["git", "-C", ROOT, *args], capture_output=True,
                         text=True, check=False).stdout
    return out.rstrip("\n") if raw else out.strip()


def status_map():
    d = {"M": "modified", "A": "added", "D": "deleted", "R": "renamed",
         "??": "untracked", "AM": "added, then modified"}
    return d


def collect():
    rows = []
    for line in git("status", "--porcelain", raw=True).splitlines():
        if not line.strip():
            continue
        st, path = line[:2].strip(), line[2:].strip().strip('"')
        if "->" in path:
            path = path.split("->")[-1].strip()
        # This document is written by this script, so counting it would make the inventory a
        # function of whether the tool had been run yet.
        if os.path.abspath(os.path.join(ROOT, path)) == os.path.abspath(OUT):
            continue
        full = os.path.join(ROOT, path)
        try:
            stt = os.stat(full)
            size, mtime = stt.st_size, datetime.fromtimestamp(stt.st_mtime)
        except OSError:
            size, mtime = None, None
        rows.append(dict(path=path, status=st, size=size, mtime=mtime))
    rows.sort(key=lambda r: (r["mtime"] or datetime.min, r["path"]))
    return rows


def episode_of(mtime):
    if mtime is None:
        return None
    for lo, hi, name, why in EPISODES:
        if datetime.strptime(lo, "%Y-%m-%d %H:%M") <= mtime <= \
                datetime.strptime(hi, "%Y-%m-%d %H:%M"):
            return name, why
    return None


def human(n):
    if n is None:
        return "—"
    for unit in ("B", "KB", "MB"):
        if n < 1024 or unit == "MB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024.0


def diffstat():
    """lines-changed per tracked file, so 'how big is this edit' is visible in the table."""
    out = {}
    for line in git("diff", "--numstat", raw=True).splitlines():
        parts = line.split("\t")
        if len(parts) == 3:
            add, dele, path = parts
            out[path] = ("binary" if add == "-" else f"+{add}/−{dele}")
    return out


def main():
    rows, ds, smap = collect(), diffstat(), status_map()
    groups = defaultdict(list)
    for r in rows:
        ep = episode_of(r["mtime"])
        groups[ep[0] if ep else "unclustered"].append(r)
    why_of = {name: why for _, _, name, why in EPISODES}

    L = ["# Dirty-file triage — a worklist to disposition before figure freeze\n",
         f"Generated by `code/experiments/68_dirty_triage.py` at `{git('rev-parse', '--short', 'HEAD')}` "
         f"on {datetime.now():%Y-%m-%d %H:%M}. Re-run it to refresh.\n",
         f"**{len(rows)} uncommitted paths.** This script reads the working tree and does not "
         "change it: nothing here has been committed, deleted, or stashed. The decisions are "
         "Aimee's; this document only makes them visible.\n",
         "The count is live, so it can exceed the 44 pre-existing files: any in-flight E7 script "
         "that has not been committed yet also shows up, and drops off once it is. This document "
         "excludes only itself.\n",
         "The **origin** column is a guess and is labelled as one. It rests on observable signals, "
         "not intuition: files written in the same second came from one process, the diff says "
         "what changed, and generated documents carry a `Generated by ... at <commit>` header that "
         "dates them. Where a guess is weak, the entry says so.\n",
         "## Why this list matters\n",
         "Two of this project's results were produced by code that is not in the repository: "
         "E6b's compute script was deleted before it was ever committed, and E5a's nuisance "
         "machinery was never committed at all. Both were reconstructed after the fact. Every "
         "source edit in the list below is a chance for that to happen again, which is why the "
         "source files are called out separately from the regenerable outputs.\n"]

    order = [n for _, _, n, _ in EPISODES if n in groups] + \
            (["unclustered"] if "unclustered" in groups else [])
    L.append("## Inventory, grouped by the episode that appears to have written it\n")
    for name in order:
        g = groups[name]
        L.append(f"### {name} — {len(g)} file(s)\n")
        if name in why_of:
            L.append(f"*Guess: {why_of[name]}*\n")
        else:
            L.append("*No timestamp cluster matched these; treat the origin as unknown.*\n")
        L.append("| path | state | size | last modified | change | note |")
        L.append("|---|---|---:|---|---:|---|")
        for r in g:
            note = NOTES.get(r["path"], "")
            L.append(f"| `{r['path']}` | {smap.get(r['status'], r['status'])} | "
                     f"{human(r['size'])} | "
                     f"{r['mtime']:%Y-%m-%d %H:%M:%S} | {ds.get(r['path'], '—')} | {note} |")
        L.append("")

    dupes = defaultdict(list)
    for r in rows:
        if r["path"].endswith(".png") and r["size"]:
            dupes[(os.path.basename(r["path"]), r["size"])].append(r["path"])
    dupes = {k: v for k, v in dupes.items() if len(v) > 1}
    if dupes:
        L.append("## Figures that are dirty at more than one path\n")
        L.append("Same filename and same byte count, so these are copies of one render. Freezing "
                 "them as separate files lets them drift apart later.\n")
        for (base, size), paths in sorted(dupes.items()):
            L.append(f"- `{base}` ({human(size)}) at {len(paths)} paths:")
            for p in sorted(paths):
                L.append(f"  - `{p}`")
        L.append("")

    L.append("## Suggested disposition by category\n")
    L.append("| category | suggested action |")
    L.append("|---|---|")
    for cat, act in DISPOSITION:
        L.append(f"| {cat} | {act} |")
    L.append("")
    L.append("## What this document does not do\n")
    L.append("It does not decide anything. No file listed here was committed, deleted, or "
             "stashed, and the counts above will change the moment any of them is. Re-run the "
             "generator rather than editing this file by hand.\n")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(L))
    print(f"wrote {os.path.relpath(OUT, ROOT)} ({len(rows)} paths, "
          f"{len(order)} episode groups, {len(dupes)} duplicated figures)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
