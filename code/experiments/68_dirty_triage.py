#!/usr/bin/env python3
"""E7d: inventory every uncommitted file so it can be dispositioned before figure freeze.

Writes `outputs/_handoff/DIRTY_FILES_TRIAGE.md`. It reads the working tree and never changes it:
nothing is committed, deleted, or stashed. It is a generator rather than a hand-written list so
the worklist can be refreshed as files are dispositioned instead of going stale the first time
someone commits one.

The origin column is a GUESS, and it is labelled as one. It is grounded in three observable
signals rather than intuition: the modification timestamp (files touched in the same second were
written by one process), the diff content, and whether the file names its own generator in a
"Generated by ..." header. Where the guess is uncertain the entry says so.
"""
