#!/usr/bin/env python3
"""E7c workflow checks. Run as `make check`, or `python code/experiments/70_workflow_checks.py`.

Each check exists because something specific went wrong once:

  * PRESPEC APPEND-ONLY. A pre-registration is only worth something if it cannot be edited after
    the fact. "Amendments are append-only" is a promise about history, so it is checked against
    history: every commit touching a prespec must add lines and delete none. Both existing
    prespecs already satisfy this (E5 +212/-0, E6 +308/-0), so it is enforced over the whole
    history with no grandfathering.
  * PRESPEC TAGGED. A prespec commit that is not tagged is hard to point at later, and "the
    threshold was fixed before the compute" is a claim about ordering that a tag makes checkable.
  * REGENERATION. MENTOR_PACKET.md was hand-edited, then silently overwritten the next time its
    generator ran, and the edits were gone. So the committed file is asserted to be byte-identical
    to what the generator produces: a hand-edit now fails the check instead of quietly dying.
  * NO STALE GENERATED HEADERS. Documents that record "Generated by X at <commit>" are checked
    against the commit they name, so stale output is visible rather than mistaken for current.

Exit code is non-zero if any selected check fails, so it is usable in CI as-is.
"""
import argparse
import filecmp
import os
import re
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
PRESPEC_GLOB = os.path.join("outputs", "experiments")
# The tag whose commit introduced the "prespecs get a commit and a tag" rule. Prespecs older than
# this are reported, not failed: see check_tags.
RULE_TAG = "prespec-e7"
GENERATED = [  # (committed file, generator script, extra env)
    (os.path.join("outputs", "MENTOR_PACKET.md"),
     os.path.join("code", "experiments", "49_mentor_packet.py"), {}),
]


def git(*args, raw=False, check=False):
    r = subprocess.run(["git", "-C", ROOT, *args], capture_output=True, text=True, check=False)
    if check and r.returncode != 0:
        raise SystemExit(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout.rstrip("\n") if raw else r.stdout.strip()


def prespec_files():
    out = []
    d = os.path.join(ROOT, PRESPEC_GLOB)
    if os.path.isdir(d):
        for n in sorted(os.listdir(d)):
            if "PRESPEC" in n and n.endswith(".md"):
                out.append(os.path.join(PRESPEC_GLOB, n))
    return out


# ------------------------------------------------------------------ checks
def check_append_only():
    print("== prespec history is append-only ==")
    ok = True
    for rel in prespec_files():
        commits = git("log", "--format=%H", "--", rel).split()
        if not commits:
            print(f"  {rel}: not committed yet — SKIP")
            continue
        bad = []
        adds = dels = 0
        for c in commits:
            ns = git("show", "--format=", "--numstat", c, "--", rel, raw=True)
            for line in ns.splitlines():
                parts = line.split("\t")
                if len(parts) != 3:
                    continue
                a, d = parts[0], parts[1]
                if a == "-" or d == "-":
                    continue
                adds += int(a)
                dels += int(d)
                if int(d) > 0:
                    subj = git("show", "-s", "--format=%h %s", c)
                    bad.append(f"{subj} (−{d})")
        status = "OK" if not bad else "VIOLATION"
        print(f"  {rel}: {len(commits)} commit(s), +{adds}/−{dels}  {status}")
        for b in bad:
            print(f"      rewrote committed text: {b}")
        ok &= not bad
    return ok


def check_tags():
    """Every prespec introduced at or after the tagging rule must carry a tag.

    Prespecs that predate the rule are listed, not failed. Backfilling tags onto older commits
    would rewrite shared history to satisfy a rule those commits were not made under, and whether
    to do it is a call for the repository owner rather than for this check.
    """
    print("== each prespec commit is tagged (rule applies from `prespec-e7` onward) ==")
    tags = {t: git("rev-list", "-n1", t) for t in git("tag").split() if t}
    rule_since = tags.get(RULE_TAG)
    ok, legacy = True, []
    for rel in prespec_files():
        commits = git("log", "--format=%H", "--", rel).split()
        if not commits:
            print(f"  {rel}: not committed yet — SKIP")
            continue
        first = commits[-1]
        hit = [t for t, sha in tags.items() if sha in commits]
        if hit:
            print(f"  {rel}: tagged {', '.join(sorted(hit))}  OK")
            continue
        in_scope = bool(rule_since) and subprocess.run(
            ["git", "-C", ROOT, "merge-base", "--is-ancestor", rule_since, first],
            capture_output=True).returncode == 0
        if in_scope:
            print(f"  {rel}: NO TAG, and it postdates the rule; introduced at {first[:9]}  "
                  f"VIOLATION")
            ok = False
        else:
            print(f"  {rel}: untagged, predates the rule (introduced at {first[:9]})  legacy")
            legacy.append((rel, first[:9]))
    if legacy:
        print(f"  {len(legacy)} prespec(s) predate the tagging rule and are left alone. To tag "
              f"them, decide deliberately and run e.g.:")
        for rel, sha in legacy:
            name = os.path.basename(rel).split("_")[0].lower()
            print(f"      git tag -a prespec-{name} {sha} -m '{os.path.basename(rel)}'")
    return ok


def check_regeneration(fix=False):
    """Assert the COMMITTED file is byte-identical to what its generator produces.

    The comparison is against HEAD rather than against the working tree, because the failure this
    exists to catch is a hand edit that got committed. Comparing to the working tree would pass
    for a hand edit that has not been regenerated over yet, which is exactly the window in which
    MENTOR_PACKET.md's edits were lost.
    """
    print("== committed generated files are byte-identical to their generator's output ==")
    ok = True
    for rel, gen, env in GENERATED:
        target = os.path.join(ROOT, rel)
        if not os.path.exists(target):
            print(f"  {rel}: missing  VIOLATION")
            ok = False
            continue
        # The generators write in place, so the committed bytes are saved and restored around the
        # run. A check must not be able to change the thing it is checking.
        with tempfile.TemporaryDirectory() as td:
            backup = os.path.join(td, "before")
            shutil.copy2(target, backup)
            e = dict(os.environ, **env)
            r = subprocess.run([sys.executable, os.path.join(ROOT, gen)],
                               cwd=ROOT, capture_output=True, text=True, env=e)
            if r.returncode != 0:
                print(f"  {rel}: generator {gen} exited {r.returncode}  VIOLATION")
                print("      " + (r.stderr.strip().splitlines() or ["(no stderr)"])[-1])
                shutil.copy2(backup, target)
                ok = False
                continue
            committed = os.path.join(td, "head")
            r2 = subprocess.run(["git", "-C", ROOT, "show", f"HEAD:{rel}"],
                                capture_output=True)
            if r2.returncode != 0:
                print(f"  {rel}: not committed at HEAD  VIOLATION")
                shutil.copy2(backup, target)
                ok = False
                continue
            open(committed, "wb").write(r2.stdout)
            same = filecmp.cmp(committed, target, shallow=False)
            if not filecmp.cmp(committed, backup, shallow=False):
                print(f"  {rel}: note — working tree differs from HEAD; the check below is "
                      f"against HEAD")
            if same:
                print(f"  {rel}: OK (regenerating reproduces the committed file exactly)")
            else:
                nb, na = os.path.getsize(committed), os.path.getsize(target)
                print(f"  {rel}: DIFFERS from `{gen}` output  VIOLATION")
                print(f"      committed {nb} B, regenerated {na} B")
                d = subprocess.run(["diff", "-u", committed, target], capture_output=True,
                                   text=True)
                for line in d.stdout.splitlines()[2:12]:
                    print(f"      {line}")
                print("      A hand edit here cannot survive the next regeneration: either patch "
                      "the generator, or commit the regenerated file.")
                if not fix:
                    shutil.copy2(backup, target)   # leave the tree as we found it
                ok = False
    return ok


def check_generated_headers():
    print("== 'Generated by X at <commit>' headers name a commit that is still current ==")
    pat = re.compile(r"Generated by `?([\w/\.\-]+\.py)`? at `?([0-9a-f]{7,40})`?")
    head = git("rev-parse", "HEAD")
    ok, checked = True, 0
    for base, _dirs, files in os.walk(os.path.join(ROOT, "outputs", "paper")):
        for n in sorted(files):
            if not n.endswith(".md"):
                continue
            p = os.path.join(base, n)
            rel = os.path.relpath(p, ROOT)
            try:
                first = open(p, encoding="utf-8").read(2000)
            except OSError:
                continue
            m = pat.search(first)
            if not m:
                continue
            checked += 1
            gen, sha = m.group(1), m.group(2)
            # A header is stale if the generator has been committed to since the header was cut.
            newer = git("log", "--format=%h", f"{sha}..{head}", "--", gen).split()
            if newer:
                print(f"  {rel}: says {sha}, but {gen} has {len(newer)} commit(s) since  STALE")
                ok = False
            else:
                print(f"  {rel}: {sha} OK")
    if not checked:
        print("  no headers of that form found")
    return ok


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--append-only", action="store_true")
    ap.add_argument("--tags", action="store_true")
    ap.add_argument("--regeneration", action="store_true")
    ap.add_argument("--headers", action="store_true")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--fix", action="store_true",
                    help="with --regeneration, leave the regenerated file in place")
    a = ap.parse_args()
    sel = dict(append_only=a.append_only, tags=a.tags,
               regeneration=a.regeneration, headers=a.headers)
    if a.all or not any(sel.values()):
        sel = {k: True for k in sel}

    results = {}
    if sel["append_only"]:
        results["prespec append-only"] = check_append_only()
    if sel["tags"]:
        results["prespec tagged"] = check_tags()
    if sel["regeneration"]:
        results["regeneration byte-identical"] = check_regeneration(a.fix)
    if sel["headers"]:
        results["generated headers current"] = check_generated_headers()

    print("\n== summary ==")
    for k, v in results.items():
        print(f"  {'PASS' if v else 'FAIL'}  {k}")
    failed = [k for k, v in results.items() if not v]
    if failed:
        print(f"\n{len(failed)} check(s) failed: {', '.join(failed)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
